# Builds data.js from the official GPX files and the closure list on the official closure map
# (https://nnmarathonthehague.nl/wp-content/uploads/sites/64/2026/10/MTH26_Afsluitingen-V3-2-scaled.jpg).
# The km ranges come from matching the image's arrows to the GPX course (tools/fit.py).
import re, math, json

def load(f):
    return [[float(lon), float(lat)] for lat, lon in re.findall(r'lat="([\d.]+)" lon="([\d.]+)"', open(f).read())]

def cum_km(pts):
    out = [0.0]
    for a, b in zip(pts, pts[1:]):
        out.append(out[-1] + math.hypot((b[1]-a[1])*111.2, (b[0]-a[0])*111.2*math.cos(math.radians(52.05))))
    return out

def interp(pts, km, k):
    for i in range(1, len(km)):
        if km[i] >= k:
            t = (k-km[i-1])/(km[i]-km[i-1]) if km[i] > km[i-1] else 0
            a, b = pts[i-1], pts[i]
            return [round(a[0]+(b[0]-a[0])*t, 6), round(a[1]+(b[1]-a[1])*t, 6)]
    return pts[-1]

def slice_line(pts, km, k0, k1):
    return [interp(pts, km, k0)] + [p for p, k in zip(pts, km) if k0 < k < k1] + [interp(pts, km, k1)]

